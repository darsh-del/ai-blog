def _parse_email_list(raw_value: str) -> list:
    """Parse comma, semicolon, or space-separated list of email addresses into a clean list."""
    if not raw_value:
        return []
    cleaned = str(raw_value).replace(";", ",").replace("\n", ",")
    addresses = []
    for item in cleaned.split(","):
        sub_items = item.strip().split()
        for sub in sub_items:
            addr = sub.strip().strip("'\"<>")
            if addr and "@" in addr and addr not in addresses:
                addresses.append(addr)
    return addresses


